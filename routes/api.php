<?php

use App\Http\Controllers\Api\AuthController;
use App\Http\Controllers\Api\AcademicController;
use App\Http\Controllers\Api\DashboardController;
use App\Http\Controllers\Api\EndorsementController;
use App\Http\Controllers\Api\InterventionController;
use App\Http\Controllers\Api\AccountController;
use App\Http\Controllers\Api\MaterialController;
use App\Http\Controllers\Api\ReportController;
use App\Http\Controllers\Api\SettingsController;
use App\Http\Controllers\Api\StudentController;
use Illuminate\Support\Facades\Route;

Route::get('/health', fn () => response()->json(['status' => 'ok']));
Route::post('/auth/login', [AuthController::class, 'login']);
Route::post('/auth/register', [AuthController::class, 'register']);

Route::middleware('auth:sanctum')->group(function () {
    Route::get('/auth/me', [AuthController::class, 'me']);
    Route::post('/auth/logout', [AuthController::class, 'logout']);
    Route::get('/dashboard', [DashboardController::class, 'show']);
    Route::get('/students/{student}/image', [StudentController::class, 'image']);
    Route::get('/students/{student}/details', [StudentController::class, 'details']);
    Route::apiResource('students', StudentController::class);
    Route::get('/assessments', [AcademicController::class, 'assessments']);
    Route::post('/assessments', [AcademicController::class, 'recordAssessment']);
    Route::get('/progress-updates', [AcademicController::class, 'progress']);
    Route::post('/progress-updates', [AcademicController::class, 'addProgress']);
    Route::get('/grade-categories', [AcademicController::class, 'categories']);
    Route::post('/grade-categories', [AcademicController::class, 'saveCategory']);
    Route::put('/grade-categories/{category}', [AcademicController::class, 'saveCategory']);
    Route::delete('/grade-categories/{category}', [AcademicController::class, 'deleteCategory']);
    Route::get('/schedule', [AcademicController::class, 'schedule']);
    Route::post('/schedule', [AcademicController::class, 'addSchedule']);
    Route::get('/remedial-sessions', [InterventionController::class, 'sessions']);
    Route::post('/remedial-sessions', [InterventionController::class, 'schedule']);
    Route::get('/attendance', [InterventionController::class, 'attendance']);
    Route::post('/attendance', [InterventionController::class, 'recordAttendance']);
    Route::get('/endorsements', [EndorsementController::class, 'index']);
    Route::get('/endorsements/{endorsement}', [EndorsementController::class, 'show']);
    Route::get('/endorsements/{endorsement}/document', [EndorsementController::class, 'document']);
    Route::post('/endorsements', [EndorsementController::class, 'submit']);
    Route::post('/endorsements/{endorsement}/review', [EndorsementController::class, 'review']);
    Route::get('/endorsements/{endorsement}/history', [EndorsementController::class, 'history']);
    Route::get('/materials', [MaterialController::class, 'index']);
    Route::post('/materials', [MaterialController::class, 'upload']);
    Route::put('/materials/{material}', [MaterialController::class, 'update']);
    Route::delete('/materials/{material}', [MaterialController::class, 'destroy']);
    Route::get('/materials/{material}/file', [MaterialController::class, 'file']);
    Route::get('/profile', [AccountController::class, 'profile']);
    Route::put('/profile', [AccountController::class, 'updateProfile']);
    Route::post('/profile/password', [AccountController::class, 'updatePassword']);
    Route::post('/profile/image', [AccountController::class, 'uploadProfileImage']);
    Route::post('/profile/toggle-status', [AccountController::class, 'toggleMyStatus']);
    Route::get('/users/{user}/image', [AccountController::class, 'image']);
    Route::get('/teachers', [AccountController::class, 'teachers']);
    Route::get('/teachers/{teacher}/profile', [AccountController::class, 'teacherProfile']);
    Route::get('/teachers/principal', [AccountController::class, 'principal']);
    Route::put('/teachers/principal', [AccountController::class, 'updatePrincipal']);
    Route::post('/teachers/principal/{action}', [AccountController::class, 'principalAction'])->whereIn('action', ['toggle', 'reset-password']);
    Route::post('/teachers', [AccountController::class, 'createTeacher']);
    Route::put('/teachers/{teacher}', [AccountController::class, 'updateTeacher']);
    Route::post('/teachers/{teacher}/{action}', [AccountController::class, 'teacherAction'])->whereIn('action', ['toggle', 'reset-password', 'delete']);
    Route::get('/settings', [SettingsController::class, 'show']);
    Route::put('/settings', [SettingsController::class, 'update']);
    Route::get('/reports', [ReportController::class, 'index']);
    Route::post('/reports', [ReportController::class, 'generate']);
    Route::get('/reports/{report}/download', [ReportController::class, 'download']);
});
